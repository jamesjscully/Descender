#!/usr/bin/env python3
"""Generate the Path 2 descent/SIS binding assumption surface."""

from __future__ import annotations

import json
from math import ceil
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[2]
FEASIBILITY_JSON = ROOT / "research/path2_descent_sis_feasibility.json"
OUT_JSON = ROOT / "research/path2_descent_sis_binding_surface.json"
OUT_MD = ROOT / "research/path2_descent_sis_binding_surface.md"

Q = 12_289
Q_BITS = 14
PRIMARY_ROW_BANDS = [48, 64]

ROLE_SURFACE = [
    {
        "role": "pad_source",
        "role_id": 1,
        "columns": 30,
        "secret_lanes": 6,
        "blinding_or_noise_lanes": 24,
        "range_witness_lanes": 0,
        "binding_scope": "binds the hidden pad-source lanes and their hiding randomness",
    },
    {
        "role": "projection_relation",
        "role_id": 2,
        "columns": 30,
        "secret_lanes": 6,
        "blinding_or_noise_lanes": 24,
        "range_witness_lanes": 0,
        "binding_scope": "binds the hidden account-projection lanes and their hiding randomness",
    },
    {
        "role": "opening_tuple",
        "role_id": 3,
        "columns": 48,
        "secret_lanes": 8,
        "blinding_or_noise_lanes": 32,
        "range_witness_lanes": 8,
        "binding_scope": "binds the scalarized hidden opening tuple and range witnesses",
    },
    {
        "role": "transcript_commitment",
        "role_id": 4,
        "columns": 108,
        "secret_lanes": 20,
        "blinding_or_noise_lanes": 80,
        "range_witness_lanes": 8,
        "binding_scope": (
            "binds an optional aggregate transcript/vector commitment over the three "
            "main role openings; this belongs to the proof layer unless the final "
            "payload verifier explicitly admits it as a separate commitment"
        ),
    },
]


def packed_q_bytes(lanes: int) -> int:
    return ceil(lanes * Q_BITS / 8)


def load_feasibility() -> dict[str, Any]:
    return json.loads(FEASIBILITY_JSON.read_text())


def build_model() -> dict[str, Any]:
    feasibility = load_feasibility()
    primary_rows = {
        row["sis_rows_per_commitment"]: row
        for row in feasibility["candidate_rows"]
        if row["sis_rows_per_commitment"] in PRIMARY_ROW_BANDS
    }
    row_band_surface = []
    for rows in PRIMARY_ROW_BANDS:
        candidate = primary_rows[rows]
        row_band_surface.append(
            {
                "rows_per_commitment": rows,
                "single_commitment_bytes": packed_q_bytes(rows),
                "three_main_role_commitment_bytes": 3 * packed_q_bytes(rows),
                "transcript_role_commitment_bytes": packed_q_bytes(rows),
                "candidate_payload_bytes_lower_bound": candidate[
                    "payload_bytes_lower_bound"
                ],
                "candidate_verifier_mul_adds": candidate[
                    "verifier_mul_adds_for_commitment_checks"
                ],
            }
        )

    return {
        "schema": "Descender.path2_descent_sis_binding_surface.v1",
        "status": "binding_game_pinned_not_hardness_claim",
        "q": Q,
        "matrix_source": {
            "artifact": "research/path2_descent_sis_matrix_domains.md",
            "rule": (
                "A_role,rowband is generated by SHA-256 rejection sampling from "
                "the role-separated Path 2 descent/SIS matrix domain, role id, "
                "row band, row, column, and counter"
            ),
        },
        "commitment_equation": {
            "form": "C = A_role,rowband * v mod q",
            "notes": (
                "The opening vector v includes semantic lanes, blinding/noise "
                "lanes, and any range-witness lanes allocated to that role. "
                "There is no separate error vector in this surface; adding one "
                "would create a different binding assumption and byte model."
            ),
        },
        "binding_break_game": {
            "name": "path2_sis_binding_break",
            "adversary_output": "(role, row_band, C, v0, v1)",
            "winning_conditions": [
                "role is one of the registered Path 2 descent/SIS commitment roles",
                "row_band is 48 or 64",
                "v0 and v1 are canonical openings for the role",
                "v0 and v1 satisfy the future per-role shortness/range bounds",
                "v0 != v1 as integer opening vectors",
                "A_role,rowband * v0 = C mod q",
                "A_role,rowband * v1 = C mod q",
            ],
            "exported_sis_witness": "delta = v0 - v1, delta != 0, A_role,rowband * delta = 0 mod q",
        },
        "role_surface": ROLE_SURFACE,
        "row_band_surface": row_band_surface,
        "blocked_on": [
            {
                "id": "p2_sis_norm_range",
                "reason": (
                    "binding hardness cannot be quantified until each role has "
                    "integer canonicalization, norm bounds, rejection behavior, "
                    "and modular-wrap controls"
                ),
            },
            {
                "id": "path2_sis_hardness_estimator",
                "reason": (
                    "after norm bounds are fixed, run a SIS/module-SIS attack "
                    "sanity estimator for each role, row band, and bound"
                ),
            },
            {
                "id": "p2_sis_extractor",
                "reason": (
                    "the final hidden-source theorem must show where the binding "
                    "break is exported inside the accepting-payload extractor"
                ),
            },
        ],
        "non_claims": [
            "this is not a numeric security estimate",
            "this is not a proof that the selected 48/64 row bands are hard",
            "this does not close p2_sis_binding by itself",
            "this does not define hiding or zero knowledge",
        ],
    }


def write_markdown(model: dict[str, Any]) -> str:
    lines = [
        "# Path 2 Descent/SIS Binding Surface",
        "",
        "Status: binding game pinned; not a hardness claim.",
        "",
        "## Commitment Equation",
        "",
        "```text",
        model["commitment_equation"]["form"],
        "```",
        "",
        model["commitment_equation"]["notes"],
        "",
        "## Binding Break Game",
        "",
        f"Name: `{model['binding_break_game']['name']}`.",
        "",
        f"Adversary output: `{model['binding_break_game']['adversary_output']}`.",
        "",
        "Winning conditions:",
        "",
    ]
    for item in model["binding_break_game"]["winning_conditions"]:
        lines.append(f"- {item}")
    lines.extend(
        [
            "",
            "Exported SIS witness:",
            "",
            "```text",
            model["binding_break_game"]["exported_sis_witness"],
            "```",
            "",
            "## Role Surface",
            "",
            "| role | id | columns | secret | blind/noise | range | binding scope |",
            "|---|---:|---:|---:|---:|---:|---|",
        ]
    )
    for role in model["role_surface"]:
        lines.append(
            "| {role} | {role_id} | {columns} | {secret_lanes} | "
            "{blinding_or_noise_lanes} | {range_witness_lanes} | "
            "{binding_scope} |".format(**role)
        )
    lines.extend(
        [
            "",
            "## Row Bands",
            "",
            "| rows | one commitment bytes | three main commitments | transcript role commitment | payload lower bound | verifier mul-adds |",
            "|---:|---:|---:|---:|---:|---:|",
        ]
    )
    for row in model["row_band_surface"]:
        lines.append(
            "| {rows_per_commitment} | {single_commitment_bytes} | "
            "{three_main_role_commitment_bytes} | {transcript_role_commitment_bytes} | "
            "{candidate_payload_bytes_lower_bound} | {candidate_verifier_mul_adds} |".format(
                **row
            )
        )
    lines.extend(["", "## Blocked On", ""])
    for item in model["blocked_on"]:
        lines.append(f"- `{item['id']}`: {item['reason']}")
    lines.extend(["", "## Non-Claims", ""])
    for item in model["non_claims"]:
        lines.append(f"- {item}")
    lines.extend(
        [
            "",
            "## Interpretation",
            "",
            "This artifact is useful because it removes ambiguity from the binding row:",
            "a double opening to a fixed role commitment must become an explicit short",
            "kernel vector for the exact Path 2 matrix domain and row band. It does not",
            "yet justify the row bands. The next useful proof move is to define the",
            "per-role canonical integer bounds, because those bounds determine whether",
            "the exported kernel vector is inside a credible SIS hardness regime.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    model = build_model()
    OUT_JSON.write_text(json.dumps(model, indent=2, sort_keys=True) + "\n")
    OUT_MD.write_text(write_markdown(model))
    print(json.dumps({"json": str(OUT_JSON), "markdown": str(OUT_MD)}, indent=2))


if __name__ == "__main__":
    main()
