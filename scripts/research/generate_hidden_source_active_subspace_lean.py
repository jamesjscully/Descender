#!/usr/bin/env python3
"""Generate the Lean active-subspace certificate from the replay JSON."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from textwrap import dedent


ROOT = Path(__file__).resolve().parents[2]
READINESS_DIR = ROOT / "research/cryptanalysis/signature_readiness_20260516"
SOURCE_JSON = (
    READINESS_DIR
    / "hidden_source_fallback_projection_active_subspace_exact_replay_n32_q12289.json"
)
OUTPUT_LEAN = ROOT / "Descender/Generated/HiddenSourceActiveSubspaceN32Q12289.lean"


def lean_string(value: str) -> str:
    return json.dumps(value)


def symbol_literal(symbol: dict[str, int]) -> str:
    return (
        "    { lane := "
        f"{symbol['lane']}, sourceColumn := {symbol['source_column']}, "
        f"coefficientModQ := {symbol['coefficient_mod_q']} }}"
    )


def render(payload: dict) -> str:
    target = payload["target"]
    coverage = payload["coverage"]
    prior = payload["prior_survivor_replay"]
    symbols = payload["active_projection_symbols"]
    source_rel = SOURCE_JSON.relative_to(ROOT).as_posix()
    source_sha = hashlib.sha256(SOURCE_JSON.read_bytes()).hexdigest()
    symbol_rows = ",\n".join(symbol_literal(symbol) for symbol in symbols)

    return dedent(
        f"""\
        import Descender.HiddenSourceActiveSubspace
        import Descender.Generated.ResponseLinkExactCertificateN32Q12289Coords03B96

        namespace Descender
        namespace HiddenSourceActiveSubspace
        namespace Generated
        namespace HiddenSourceActiveSubspaceN32Q12289

        /-!
        Generated by `scripts/research/generate_hidden_source_active_subspace_lean.py`.

        Source artifact:
        `{source_rel}`

        Source SHA-256:
        `{source_sha}`

        Source active-subspace digest:
        `{target["active_subspace_digest"]}`
        -/

        def sourcePath : String := {lean_string(source_rel)}
        def sourceSha256 : String := {lean_string(source_sha)}
        def activeSubspaceDigest : String :=
          {lean_string(target["active_subspace_digest"])}

        def q : Nat := {target["q"]}
        instance : NeZero q := by
          unfold q
          infer_instance
        instance : Fact (Nat.Prime q) := by
          unfold q
          exact ⟨by norm_num⟩

        def oldProjectionColumns : Nat := {target["source_projection_columns_in_old_model"]}
        def activeProjectionLanes : Nat := {target["active_projection_lanes"]}
        def oldSurvivorColumn : Nat := {prior["space_column"]}
        def envelopeBytes : Nat := {target["envelope_bytes"]}
        def carrierBytes : Nat := {target["carrier_bytes"]}
        def responseLinkBound : Nat := {target["bound"]}

        def activeSymbols : List ActiveLaneSymbol :=
          [
        {symbol_rows}
          ]

        theorem activeSymbols_length :
            activeSymbols.length = activeProjectionLanes := by
          native_decide

        theorem activeSourceColumns_nodup :
            (sourceColumns activeSymbols).Nodup := by
          native_decide

        theorem activeLaneIndices_nodup :
            (laneIndices activeSymbols).Nodup := by
          native_decide

        theorem allActiveColumns_lt :
            allColumnsBelow oldProjectionColumns activeSymbols := by
          intro s hs
          simp [activeSymbols, oldProjectionColumns] at hs ⊢
          rcases hs with
            rfl | rfl | rfl | rfl | rfl | rfl | rfl | rfl | rfl | rfl | rfl | rfl
          all_goals decide

        theorem allActiveLanes_lt :
            allLanesBelow activeProjectionLanes activeSymbols := by
          intro s hs
          simp [activeSymbols, activeProjectionLanes] at hs ⊢
          rcases hs with
            rfl | rfl | rfl | rfl | rfl | rfl | rfl | rfl | rfl | rfl | rfl | rfl
          all_goals decide

        theorem oldSurvivorColumn_excluded :
            survivorExcluded oldSurvivorColumn activeSymbols := by
          unfold survivorExcluded sourceColumns oldSurvivorColumn activeSymbols
          decide

        theorem inactiveProjectionColumns_eq :
            oldInactiveProjectionColumns oldProjectionColumns activeSymbols =
              {coverage["old_inactive_projection_columns"]} := by
          native_decide

        theorem activeCoefficientsNonzero_q12289 :
            coefficientsNonzeroModQ q activeSymbols := by
          unfold q coefficientsNonzeroModQ
          native_decide

        def certificate : ActiveSubspaceCertificate q where
          oldProjectionColumns := oldProjectionColumns
          activeProjectionLanes := activeProjectionLanes
          survivorColumn := oldSurvivorColumn
          symbols := activeSymbols
          symbols_length := activeSymbols_length
          sourceColumns_nodup := activeSourceColumns_nodup
          laneIndices_nodup := activeLaneIndices_nodup
          allColumns_lt := allActiveColumns_lt
          allLanes_lt := allActiveLanes_lt
          survivor_excluded := oldSurvivorColumn_excluded
          inactive_columns_eq := inactiveProjectionColumns_eq
          coefficients_nonzero := activeCoefficientsNonzero_q12289

        theorem exact_survivor_excluded_from_active_relation :
            oldSurvivorColumn ∉ sourceColumns activeSymbols :=
          certificate.old_survivor_not_active

        theorem active_projection_lane_count :
            activeSymbols.length = {coverage["active_projection_lanes"]} := by
          native_decide

        theorem active_projection_readout_detects :
            ActiveLaneReadoutDetects q activeSymbols :=
          certificate.readout_detects

        theorem inactive_projection_columns_eq_52 :
            oldInactiveProjectionColumns oldProjectionColumns activeSymbols =
              {coverage["old_inactive_projection_columns"]} :=
          certificate.inactive_projection_column_count

        theorem response_link_bound_matches_exact_certificate :
            responseLinkBound =
              Descender.ResponseLinkExactCertificate.Generated.ResponseLinkExactCertificateN32Q12289Coords03B96.summary.responseDifferenceBound := by
          native_decide

        theorem response_link_exact_certificate_excludes_active_bound :
            Descender.ResponseLinkExactCertificate.Generated.ResponseLinkExactCertificateN32Q12289Coords03B96.summary.excludesBoundedNonzeroKernel :=
          Descender.ResponseLinkExactCertificate.Generated.ResponseLinkExactCertificateN32Q12289Coords03B96.exact_certificate_excludes_bounded_nonzero_kernel

        theorem no_response_link_kernel_vector_inside_active_bound
            {{coeffBound : Nat}}
            (hle : coeffBound <= responseLinkBound)
            (hshort :
              Descender.ResponseLinkExactCertificate.Generated.ResponseLinkExactCertificateN32Q12289Coords03B96.summary.minimumCoverCoeffBound <=
                coeffBound) :
            False := by
          have hle' :
              coeffBound <=
                Descender.ResponseLinkExactCertificate.Generated.ResponseLinkExactCertificateN32Q12289Coords03B96.summary.responseDifferenceBound := by
            simpa [responseLinkBound] using hle
          exact
            Descender.ResponseLinkExactCertificate.Generated.ResponseLinkExactCertificateN32Q12289Coords03B96.no_nonzero_kernel_vector_inside_response_box
              hle' hshort

        theorem old_survivor_not_in_active_subspace :
            oldSurvivorColumn ∉ sourceColumns activeSymbols :=
          exact_survivor_excluded_from_active_relation

        end HiddenSourceActiveSubspaceN32Q12289
        end Generated
        end HiddenSourceActiveSubspace
        end Descender
        """
    )


def main() -> None:
    payload = json.loads(SOURCE_JSON.read_text())
    if payload.get("schema") != "Descender.hidden_source_fallback_projection_active_subspace_exact_replay.v1":
        raise SystemExit(f"unexpected schema in {SOURCE_JSON}")
    if payload.get("status") != "active_subspace_exact_replay_closed_inactive_survivor_excluded_fail_closed":
        raise SystemExit(f"unexpected status in {SOURCE_JSON}")
    if payload["coverage"].get("survivor_in_active_subspace") is not False:
        raise SystemExit("survivor must be excluded from the active subspace")
    if payload["coverage"].get("exact_certificate_complete_for_active_subspace") is not True:
        raise SystemExit("active subspace exact certificate must be complete")
    if payload["coverage"].get("open_row_count") != 0:
        raise SystemExit("active subspace replay must have zero open rows")

    OUTPUT_LEAN.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_LEAN.write_text(render(payload), encoding="utf-8")
    print(json.dumps({"lean": str(OUTPUT_LEAN.relative_to(ROOT))}, indent=2))


if __name__ == "__main__":
    main()
